// ---------------------------------------------------------------------------
// Vista pública del Layout: lo que abre el QR del Layout, SIN iniciar sesión. Igual que la ficha pública de un artículo (Ficha.html), no usa
// Dashboard.js: es para quien escanea el QR pegado en la nave. Lee GET /api/public/layout/:token, que solo entrega lo público (paredes, zonas,
// anaqueles/gabetas/tarimas con su código, puertas y los KPIs; nunca las conexiones de luz ni las columnas) y siempre la versión guardada más reciente.
// El QR nunca cambia: lo que cambia es lo que este token devuelve cada vez que alguien guarda el Layout.
// ---------------------------------------------------------------------------
(function () {
    const LANG = (navigator.language || 'es').toLowerCase().startsWith('en') ? 'en' : 'es';
    const TEXT = {
        es: {
            title: 'Layout de la nave', version: 'Versión', updated: 'Actualizado', zones: 'Zonas', notFound: 'Este Layout no está disponible.',
            error: 'No se pudo cargar el Layout. Intenta de nuevo.', footer: 'Layout generado por SGN',
            kpiTotal: 'Superficie total', kpiOffices: 'Oficinas', kpiAisles: 'Pasillos', kpiStorage: 'Espacios de almacenamiento', kpiDead: 'Espacios muertos', kpiVolume: 'Volumen de la nave',
            spaces: 'espacios',
            zone: { dry: 'Seco', cold: 'Refrigerado', chemical: 'Químicos', finished: 'Producto terminado', dock: 'Andén', office: 'Oficina', aisle: 'Pasillo' },
        },
        en: {
            title: 'Warehouse Layout', version: 'Version', updated: 'Updated', zones: 'Zones', notFound: 'This Layout is not available.',
            error: 'The Layout could not be loaded. Try again.', footer: 'Layout generated by SGN',
            kpiTotal: 'Total area', kpiOffices: 'Offices', kpiAisles: 'Aisles', kpiStorage: 'Storage spaces', kpiDead: 'Dead space', kpiVolume: 'Warehouse volume',
            spaces: 'spaces',
            zone: { dry: 'Dry', cold: 'Refrigerated', chemical: 'Chemicals', finished: 'Finished goods', dock: 'Dock', office: 'Office', aisle: 'Aisle' },
        },
    }[LANG];
    document.documentElement.lang = LANG;
    document.title = TEXT.title;

    const esc = (v) => String(v == null ? '' : v).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
    const fmt = (n) => (Number.isFinite(n) ? n : 0).toLocaleString(LANG === 'en' ? 'en-US' : 'es-MX', { maximumFractionDigits: 2 });
    // La base de datos guarda la hora en UTC ("2026-10-31 16:42:00"): aquí se muestra en la hora de quien escanea, con el UTC a la vista.
    function stamp(raw) {
        const date = new Date(`${String(raw).replace(' ', 'T')}Z`);
        if (Number.isNaN(date.getTime())) return '';
        const local = date.toLocaleString(LANG === 'en' ? 'en-US' : 'es-MX', { day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit' });
        return `${local} (UTC ${String(date.getUTCHours()).padStart(2, '0')}:${String(date.getUTCMinutes()).padStart(2, '0')})`;
    }

    function renderState(message) {
        document.getElementById('wrap').innerHTML = `<div class="state">${esc(message)}</div>`;
    }

    function render(data) {
        const k = data.kpis;
        const initials = (data.companyName || '').trim().slice(0, 2).toUpperCase() || '··';
        const kpis = [[k.total, 'kpiTotal'], [k.offices, 'kpiOffices'], [k.aisles, 'kpiAisles'], [k.storage, 'kpiStorage'], [k.dead, 'kpiDead'], [k.volume, 'kpiVolume']]
            .map(([value, key]) => `<div class="kpi"><b>${fmt(value)} ${key === 'kpiVolume' ? 'm³' : 'm²'}</b><span>${esc(TEXT[key])}</span></div>`);
        const zones = k.zones.map((z) => `<div class="row"><span>${esc(z.name)} · ${esc(TEXT.zone[z.type] || z.type)}</span><span>${fmt(z.area)} m²${z.spaces ? ` · ${z.spaces} ${esc(TEXT.spaces)}` : ''}</span></div>`).join('');
        document.getElementById('wrap').innerHTML = `
            <div class="brand"><span class="brand-mark">${esc(initials)}</span><span class="brand-name">${esc(data.companyName)}</span></div>
            <div class="info"><h1>${esc(TEXT.title)}</h1><p class="sub">${esc(TEXT.version)} ${data.version} · ${esc(TEXT.updated)} ${esc(stamp(data.updatedAt))}</p></div>
            <div class="map">${window.LayoutMapSvg.mapSvg(data.layout)}</div>
            <div class="kpis">${kpis.join('')}</div>
            <h2>${esc(TEXT.zones)}</h2>${zones}
            <div class="footer">${esc(TEXT.footer)}</div>`;
    }

    (async function init() {
        // /q/<token>: el token es el último tramo de la dirección.
        const token = decodeURIComponent(window.location.pathname.split('/').filter(Boolean).pop() || '');
        if (!/^[0-9a-f]{32}$/.test(token)) { renderState(TEXT.notFound); return; }
        try {
            const res = await fetch(`/api/public/layout/${encodeURIComponent(token)}`, { cache: 'no-store' });
            if (res.status === 404) { renderState(TEXT.notFound); return; }
            if (!res.ok) throw new Error('layout public failed');
            render(await res.json());
        } catch (err) {
            console.error('Layout público: no se pudo cargar', err);
            renderState(TEXT.error);
        }
    }());
}());
